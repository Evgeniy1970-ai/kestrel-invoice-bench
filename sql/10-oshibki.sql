-- Kestrel Invoice Bench — 10-oshibki.sql
-- Журнал сбоев workflow. Пишет WF-00, читает человек.
--
-- Накатывать ПОСЛЕ 02-progony.sql: таблица живёт в схеме rec.
--
-- Зачем отдельная таблица, а не rec.job_queue.
--
-- Два несовпадения, оба принципиальные.
--
-- Первое: назначение разное. job_queue — очередь работы: что осталось
-- сделать, сколько было попыток, когда повторить. Строку очереди после
-- успеха закрывают. Запись журнала не трогают никогда.
--
-- Второе: ключевые поля отсутствуют. У job_queue есть document_id и
-- run_id. При сбое приёма может не быть ни того, ни другого: если упал
-- узел Mail in, документа не существует, а прогона у приёма нет по
-- решению от 25 августа. Сделать оба поля пустыми можно, но тогда
-- очередь перестанет означать «работа над документом в прогоне».
--
-- Почему схема rec, хотя в описи сказано «rec — внутри прогонов».
-- Это ЯВНОЕ ИСКЛЮЧЕНИЕ из правила. Сбой — операционная запись, а
-- операционные записи проекта живут в rec (там же runs и job_queue).
-- Правило «rec внутри прогонов» верно для результатов измерения, а не
-- для журнала работы стенда. Альтернатива — шестая схема ops, честнее
-- по структуре, но ради одной таблицы это шестой набор прав.
-- =====================================================================

create table if not exists rec.workflow_errors (
    id              bigserial primary key,

    -- Что упало. Приходит от узла Error Trigger.
    workflow_id     text,
    workflow_name   text,

    -- Ссылка на выполнение в n8n.
    --
    -- ДОПУСКАЮТ ПУСТОТУ, и это не небрежность. Документация n8n по узлу
    -- Error Trigger: execution.id и execution.url отсутствуют, если
    -- ошибка произошла в самом триггерном узле — workflow в этом случае
    -- не выполняется вовсе. Сделать их обязательными значит уронить
    -- WF-00 ровно на самом тяжёлом виде сбоя.
    execution_id    text,
    execution_url   text,

    failed_node     text,
    error_message   text,

    -- Прогон, если сбой случился внутри него: WF-02, WF-04, WF-06.
    -- Для приёма пустой — прогона у приёма нет.
    --
    -- БЕЗ внешнего ключа на rec.runs НАМЕРЕННО. Если поставить ссылку,
    -- а прогон окажется чужим или несуществующим, запись о сбое не
    -- пройдёт — то есть механизм, созданный ловить сбои, сам упадёт на
    -- сбое. Связь проверяется запросом, а не ограничением.
    run_id          bigint,

    -- Весь пакет от Error Trigger целиком, по образцу extractions.raw_json.
    -- Единственное обязательное поле: даже если разобрать пакет не
    -- удалось, он сохранится и разберётся руками. Хранить всё дешевле,
    -- чем потом восстанавливать.
    raw_json        jsonb not null,

    created_at      timestamptz not null default now()
);

comment on table rec.workflow_errors is
    'Журнал сбоев workflow. Пишет WF-00 через Error Trigger. Только вставка, записи не правятся и не удаляются.';

comment on column rec.workflow_errors.execution_id is
    'Пусто, если ошибка в триггерном узле: workflow при этом не выполняется, и выполнения не существует.';

comment on column rec.workflow_errors.run_id is
    'Без внешнего ключа намеренно: запись о сбое обязана проходить всегда.';

create index if not exists workflow_errors_created_idx
    on rec.workflow_errors (created_at desc);
create index if not exists workflow_errors_workflow_idx
    on rec.workflow_errors (workflow_name);

-- ---------------------------------------------------------------------
-- Права.
--
-- Таблица получит права сама: для схемы rec в 07-prava.sql заданы
-- умолчания ALTER DEFAULT PRIVILEGES, проверено 30 августа запросом
-- к pg_default_acl — там {bench_pipeline=arw/postgres, bench_score=r/postgres}.
--
-- А последовательность умолчаниями НЕ покрыта: строки с типом S для
-- схемы rec в pg_default_acl нет. Без usage insert под bench_pipeline
-- упадёт с permission denied for sequence — и упадёт молча, потому что
-- это WF-00, и его собственный сбой ловить некому.
-- ---------------------------------------------------------------------

grant usage, select on sequence rec.workflow_errors_id_seq to bench_pipeline;

-- Явно, на случай если умолчания не сработали. Повторная выдача
-- уже имеющихся прав ошибки не даёт.
grant select, insert on rec.workflow_errors to bench_pipeline;
grant select          on rec.workflow_errors to bench_score;

